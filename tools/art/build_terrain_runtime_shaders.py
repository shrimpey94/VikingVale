"""Build the 1.7.6 runtime terrain shaders from the art-side cumulative shaders.

Sources (art-side, approved; copied unchanged into assets/authored/terrain/):
  surface49_batch02/v001/surface49_batch02_2d.gdshader   (crisp 2D = game base + authored)
  surface49_batch02/v001/surface49_batch02_3d.gdshader   (3D chunk material)
Game bases (unchanged):
  shaders/terrain_blend.gdshader, shaders/terrain_blend_smooth.gdshader

Outputs (generated; never hand-edit, re-run this script instead):
  shaders/terrain_authored_2d.gdshader          crisp 2D ground preference
  shaders/terrain_authored_2d_smooth.gdshader   smooth 2D ground preference
  shaders/terrain_authored_3d.gdshader          3D chunk material

The ONLY changes made to the art-side shaders:
  1. Wood/stone bridge tiles (ids 48/49) get no authored surface: the connected
     bridge kit is still in review, so bridges show the old ground under the
     placeholder bridge pieces (scripts/terrain/Bridge*.gd).
  2. The smooth variant splices the art-side authored block + final mix onto the
     game's smooth base instead of the crisp base.
The script asserts the art-side crisp base is still byte-identical to the game's
terrain_blend.gdshader, so a stale art-side copy can't silently revert game fixes.

Usage: python tools/art/build_terrain_runtime_shaders.py [--check]
  --check: verify the outputs are up to date (exit 1 if not); writes nothing.
"""
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "assets/authored/terrain/surface49_batch02/v001"
SHADERS = ROOT / "shaders"
HEADER = ("// GENERATED by tools/art/build_terrain_runtime_shaders.py from\n"
          "// assets/authored/terrain/surface49_batch02/v001/{src}. Do not edit by hand.\n")

BRIDGE_IDS_IN = (" if(id==48.0)return 33;\n", " if(id==49.0)return 34;\n")
BAND_2D = (" if(bridge_id==48.0||bridge_id==49.0){float band=fract(world_pos.y/32.0);"
           "coverage*=step(.125,band)*(1.0-step(.875,band));}\n")
NO_BRIDGE_2D = " if(bridge_id==48.0||bridge_id==49.0){coverage=0.0;}  // placeholder bridges draw on top\n"
SURFACE_3D = " surface(ground_metres,art,n,orm,coverage,world_detail);\n"
NO_BRIDGE_3D = (SURFACE_3D + " {float bridge_id=sample_id(floor(ground_metres));"
                "if(bridge_id==48.0||bridge_id==49.0)coverage=0.0;}  // bridge decks are separate meshes\n")


def read(p: Path) -> str:
    return io.open(p, encoding="utf-8", newline="").read().replace("\r\n", "\n")


def drop_bridges(text: str, name: str) -> str:
    for line in BRIDGE_IDS_IN:
        if text.count(line) != 1:
            sys.exit(f"{name}: expected exactly one {line.strip()!r}")
        text = text.replace(line, "")
    return text


def build() -> dict:
    a2d = read(SRC / "surface49_batch02_2d.gdshader")
    a3d = read(SRC / "surface49_batch02_3d.gdshader")
    crisp = read(SHADERS / "terrain_blend.gdshader")
    smooth = read(SHADERS / "terrain_blend_smooth.gdshader")

    base_mark = "uniform sampler2D atlas"
    tail_mark = " vec3 art;vec3 sn;vec3 orm;float coverage;\n"
    i_base = a2d.index(base_mark)
    i_tail = a2d.index(tail_mark)
    authored_block = a2d[a2d.index("shader_type canvas_item;\n") + len("shader_type canvas_item;\n"):i_base]
    art_tail = a2d[i_tail:a2d.rindex("}")]          # final authored mix, without the closing brace
    # The art-side base must still be the game's crisp base (minus its last COLOR line).
    crisp_base = crisp[crisp.index(base_mark):]
    crisp_end = "\tCOLOR = col;\n}\n"
    if not crisp_base.endswith(crisp_end) or a2d[i_base:i_tail] != crisp_base[:-len(crisp_end)]:
        sys.exit("art-side 2D base differs from shaders/terrain_blend.gdshader; ask for a re-export")
    if art_tail.count(BAND_2D) != 1:
        sys.exit("2D bridge band line not found")
    art_tail = art_tail.replace(BAND_2D, NO_BRIDGE_2D)

    out_crisp = HEADER.format(src="surface49_batch02_2d.gdshader") + drop_bridges(
        a2d.replace(BAND_2D, NO_BRIDGE_2D), "2d")

    smooth_end = "\tCOLOR = col;\n}\n"
    if not smooth.endswith(smooth_end):
        sys.exit("smooth base: unexpected ending")
    s_head, s_body = smooth.split("shader_type canvas_item;\n", 1)
    out_smooth = (HEADER.format(src="surface49_batch02_2d.gdshader (smooth base)") + s_head
                  + "shader_type canvas_item;\n" + drop_bridges(authored_block, "2d smooth")
                  + s_body[:-len(smooth_end)] + art_tail + "}\n")

    if a3d.count(SURFACE_3D) != 1:
        sys.exit("3D surface() call not found")
    out_3d = HEADER.format(src="surface49_batch02_3d.gdshader") + drop_bridges(
        a3d.replace(SURFACE_3D, NO_BRIDGE_3D), "3d")
    return {"terrain_authored_2d.gdshader": out_crisp,
            "terrain_authored_2d_smooth.gdshader": out_smooth,
            "terrain_authored_3d.gdshader": out_3d}


def main() -> None:
    check = "--check" in sys.argv
    stale = []
    for name, text in build().items():
        p = SHADERS / name
        if check:
            if not p.exists() or read(p) != text:
                stale.append(name)
            continue
        io.open(p, "w", encoding="utf-8", newline="").write(text)
        print(f"wrote {p.relative_to(ROOT)} ({len(text.encode('utf-8'))} bytes)")
    if check:
        print("stale: " + ", ".join(stale) if stale else "runtime terrain shaders up to date")
        sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
